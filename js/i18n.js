window.i18nLangs = ['zh', 'en'];
window.i18nLang = localStorage.getItem('nsb-lang') || 'en';

window.t = function(key) {
  if (window.i18nLang === 'zh') return key;
  if (!window.NSB_I18N.en[key]) {
    // try exact match or fallback
    return key;
  }
  return window.NSB_I18N.en[key];
};

window.toggleLang = function() {
  window.i18nLang = window.i18nLang === 'zh' ? 'en' : 'zh';
  localStorage.setItem('nsb-lang', window.i18nLang);
  location.reload();
};

window.tH = function(html) {
  if (typeof html !== 'string' || window.i18nLang === 'zh') return html;
  let res = html;
  // Sort keys by length descending to replace longer phrases first (avoids partial replacements)
  const keys = Object.keys(window.NSB_I18N.en).sort((a, b) => b.length - a.length);
  for (let k of keys) {
    // Only replace keys that have Chinese characters or specific UI strings
    if (k.match(/[\u4e00-\u9fa5]/) || k === 'English/中文') {
      res = res.split(k).join(window.NSB_I18N.en[k]);
    }
  }
  return res;
};

// Intercept all innerHTML assignments to translate them on the fly
const originalInnerHTML = Object.getOwnPropertyDescriptor(Element.prototype, 'innerHTML');
Object.defineProperty(Element.prototype, 'innerHTML', {
  get() { return originalInnerHTML.get.call(this); },
  set(val) { originalInnerHTML.set.call(this, window.tH(val)); }
});
